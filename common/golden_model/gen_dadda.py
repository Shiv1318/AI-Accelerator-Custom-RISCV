N = 8
cols = [[] for _ in range(2 * N)]
decl = []
def new(expr):
    decl.append(expr)
    return "d%d" % len(decl)
for i in range(N):
    for j in range(N):
        c = i + j
        if (i == N - 1) != (j == N - 1):
            cols[c].append(new("~(a[%d] & b[%d])" % (i, j)))
        else:
            cols[c].append(new("a[%d] & b[%d]" % (i, j)))
cols[N].append("1'b1")
cols[2 * N - 1].append("1'b1")
stages = 0
for d in [6, 4, 3, 2]:
    stages += 1
    nxt = [[] for _ in range(2 * N)]
    for c in range(2 * N):
        bits = cols[c][:]
        h = len(bits) + len(nxt[c])
        while h > d:
            if h - d >= 2 and len(bits) >= 3:
                x, y, z = bits.pop(0), bits.pop(0), bits.pop(0)
                s = new("%s ^ %s ^ %s" % (x, y, z))
                k = new("(%s & %s) | (%s & %s) | (%s & %s)" % (x, y, x, z, y, z))
                nxt[c].append(s)
                if c + 1 < 2 * N: nxt[c + 1].append(k)
                h -= 2
            else:
                x, y = bits.pop(0), bits.pop(0)
                s = new("%s ^ %s" % (x, y))
                k = new("%s & %s" % (x, y))
                nxt[c].append(s)
                if c + 1 < 2 * N: nxt[c + 1].append(k)
                h -= 1
        nxt[c].extend(bits)
    cols = nxt
assert all(len(c) <= 2 for c in cols), [len(c) for c in cols]
r0 = [c[0] if len(c) > 0 else "1'b0" for c in cols]
r1 = [c[1] if len(c) > 1 else "1'b0" for c in cols]
o = ["// Combinational 8x8 signed multiplier: Baugh-Wooley partial products,",
     "// Dadda-tree reduction (%d stages, 3:2 and 2:2), final carry-propagate add." % stages,
     "// GENERATED by software/gen_dadda.py - do not edit by hand.",
     "module mult_dadda #(parameter int W = 8) (",
     "    input  logic signed [W-1:0]   a,", "    input  logic signed [W-1:0]   b,",
     "    output logic signed [2*W-1:0] p", ");"]
for i, e in enumerate(decl): o.append("    wire d%d = %s;" % (i + 1, e))
o.append("    wire [15:0] r0 = {%s};" % ", ".join(reversed(r0)))
o.append("    wire [15:0] r1 = {%s};" % ", ".join(reversed(r1)))
o += ["    assign p = r0 + r1;", "endmodule"]
open("rtl_dadda/mult_dadda.sv", "w").write("\n".join(o) + "\n")
print("stages", stages, "wires", len(decl))
