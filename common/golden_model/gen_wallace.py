W=8; cols=[[] for _ in range(2*W)]
L=[]; n=[0]
def new(expr):
    n[0]+=1; nm=f"w{n[0]}"; L.append(f"    wire {nm} = {expr};"); return nm
for i in range(W):
    for j in range(W):
        e=f"a[{i}] & b[{j}]"
        if (i==W-1) != (j==W-1): e=f"~(a[{i}] & b[{j}])"
        cols[i+j].append(new(e))
cols[W].append("1'b1"); cols[2*W-1].append("1'b1")
stage=0
while max(len(c) for c in cols)>2:
    stage+=1; nxt=[[] for _ in range(2*W)]
    for k,c in enumerate(cols):
        i=0
        while len(c)-i>=3:
            x,y,z=c[i:i+3]; i+=3
            nxt[k].append(new(f"{x} ^ {y} ^ {z}"))
            if k+1<2*W: nxt[k+1].append(new(f"({x} & {y}) | ({x} & {z}) | ({y} & {z})"))
        if len(c)-i==2:
            x,y=c[i:i+2]; i+=2
            nxt[k].append(new(f"{x} ^ {y}"))
            if k+1<2*W: nxt[k+1].append(new(f"{x} & {y}"))
        elif len(c)-i==1: nxt[k].append(c[i])
    cols=nxt
r0=[c[0] if len(c)>0 else "1'b0" for c in cols]; r1=[c[1] if len(c)>1 else "1'b0" for c in cols]
hdr=f"""// Combinational 8x8 signed multiplier: Baugh-Wooley partial products,
// Wallace-tree (3:2 and 2:2 compressor) reduction in {stage} stages, final carry-propagate add.
// GENERATED by software/gen_wallace.py - do not edit by hand.
module mult_wallace #(parameter int W = 8) (
    input  logic signed [W-1:0]   a,
    input  logic signed [W-1:0]   b,
    output logic signed [2*W-1:0] p
);
"""
body="\n".join(L)+f"\n    wire [15:0] r0 = {{{', '.join(reversed(r0))}}};\n    wire [15:0] r1 = {{{', '.join(reversed(r1))}}};\n    assign p = r0 + r1;\nendmodule\n"
open("rtl/mult_wallace.sv","w").write(hdr+body)
